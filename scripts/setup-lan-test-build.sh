#!/usr/bin/env bash
# Prepares VoxOrd for an internal test build that talks to the dev stack over Wi-Fi.
#
# Usage:  scripts/setup-lan-test-build.sh <LAN_IP> [--rebuild-media] [--apk]
#   <LAN_IP>          IP of the computer running the dev stack, e.g. 192.168.50.200
#   --rebuild-media   recreate media-service so presigned MinIO URLs carry the LAN host
#   --apk             run ./gradlew assembleRelease at the end
#
# Idempotent: safe to run again (e.g. after the IP changes). INTERNAL TEST ONLY — before a public
# release remove android/app/src/main/res/xml/network_security_config.xml and the
# android:networkSecurityConfig attribute from AndroidManifest.xml.
set -euo pipefail

IP="${1:-}"
[[ "$IP" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]] || { echo "Usage: $0 <LAN_IP> [--rebuild-media] [--apk]" >&2; exit 1; }
shift
REBUILD=0; APK=0
for a in "$@"; do
  case "$a" in
    --rebuild-media) REBUILD=1 ;;
    --apk) APK=1 ;;
    *) echo "Unknown option: $a" >&2; exit 1 ;;
  esac
done

VOX="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PLATFORM="${PLATFORM_DIR:-$VOX/../ssz-platform}"
XML="$VOX/android/app/src/main/res/xml/network_security_config.xml"
MANIFEST="$VOX/android/app/src/main/AndroidManifest.xml"
ENVF="$PLATFORM/infrastructure/.env.dev"

# 1. Allowed cleartext hosts: LAN IP + emulator + localhost, nothing else.
mkdir -p "$(dirname "$XML")"
cat > "$XML" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!--
  INTERNAL TEST BUILD: cleartext http:// is allowed only for the named staging hosts, everything
  else stays https-only. Generated by scripts/setup-lan-test-build.sh.
  Remove this file and the manifest attribute before any public release.
-->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">$IP</domain>
        <domain includeSubdomains="false">10.0.2.2</domain>
        <domain includeSubdomains="false">localhost</domain>
    </domain-config>
</network-security-config>
EOF
echo "ok  network_security_config.xml -> $IP"

# 2. Reference the config from the manifest.
if grep -q 'android:networkSecurityConfig' "$MANIFEST"; then
  echo "ok  manifest already references the config"
else
  sed -i 's|^\( *\)android:usesCleartextTraffic="\${usesCleartextTraffic}"|&\n\1android:networkSecurityConfig="@xml/network_security_config"|' "$MANIFEST"
  grep -q 'android:networkSecurityConfig' "$MANIFEST" || { echo "manifest edit failed" >&2; exit 1; }
  echo "ok  manifest now references the config"
fi

# 3. Public MinIO host for presigned URLs.
[[ -f "$ENVF" ]] || { echo "missing $ENVF" >&2; exit 1; }
if grep -q '^MINIO_PUBLIC_BASE_URL=' "$ENVF"; then
  sed -i "s|^MINIO_PUBLIC_BASE_URL=.*|MINIO_PUBLIC_BASE_URL=http://$IP:9000|" "$ENVF"
else
  printf '\nMINIO_PUBLIC_BASE_URL=http://%s:9000\n' "$IP" >> "$ENVF"
fi
echo "ok  .env.dev MINIO_PUBLIC_BASE_URL=http://$IP:9000"

# 4. Optional: recreate media-service.
if [[ $REBUILD -eq 1 ]]; then
  (cd "$PLATFORM/infrastructure" && docker compose --env-file .env.dev -f docker-compose.base.yml -f docker-compose.dev.yml up -d --build media-service)
  echo "ok  media-service rebuilt"
fi

# 5. Optional: build the APK.
if [[ $APK -eq 1 ]]; then
  (cd "$VOX/android" && ./gradlew assembleRelease)
  echo "ok  APK: $VOX/android/app/build/outputs/apk/release/"
fi

echo "Done. In the app: Settings -> Developer -> server = http://$IP:80"
