export type IconName = keyof typeof ICONS;
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

export interface IconProps {
  name: IconName;
  size?: number;
  /** Defaults to the primary text colour of the active scheme. */
  color?: string;
  weight?: 'regular' | 'fill';
}

export function Icon({
  name,
  size = 20,
  color,
  weight = 'regular',
}: IconProps) {
  const { colors } = useTheme();
  const Glyph = ICONS[name];
  return <Glyph size={size} color={color ?? colors.text} weight={weight} />;
}
